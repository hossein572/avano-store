export const matchesSearch = (product: Product, query: string) => {
  const terms = query
    .trim()
    .split(/\s+/)
    .filter(
      (t) => t.length > 1 && !["زنانه", "محصول", "های", "برای"].includes(t),
    );
  return (
    !terms.length ||
    terms.some((t) => product.name.includes(t) || product.category.includes(t))
  );
};
